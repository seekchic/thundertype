// ============================================================
// glyphs.js — 骨格（モノライン・スケルトン）定義
//   座標は正規化: x 0..1（字幅 w 倍のボックス内）/ y 0..1（0=キャップトップ, 1=ベースライン）
//   先頭と末尾が同じ点なら「閉ループ」扱い → テーパー無し＋カウンター（穴）ができる
//
//   丸い字は八角形などで近似していたが、静かな日（変位量がほぼ 0）は骨格が
//   そのまま出るので多角形に見えてしまう。曲線は arc() で本物の楕円弧から起こす。
// ============================================================

const D2R = Math.PI / 180;

// 楕円弧上の点列。0°=右、90°=下（y 下向き）。a0→a1 を n 分割する
function arc(cx, cy, rx, ry, a0, a1, n) {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const t = (a0 + (a1 - a0) * (i / n)) * D2R;
    out.push([cx + rx * Math.cos(t), cy + ry * Math.sin(t)]);
  }
  return out;
}

// 手で打った曲線に残る面取りを均す。曲がりが浅い頂点（＝曲線の分割点）だけを
// 角切りし、急な頂点（＝意図した折れ。L の角や 2 の裾）はそのまま残す
function roundFacets(pts, maxTurn = 52, passes = 2) {
  const closed = Math.hypot(pts[0][0] - pts[pts.length - 1][0],
                            pts[0][1] - pts[pts.length - 1][1]) < 1e-9;
  let v = closed ? pts.slice(0, -1) : pts.map((p) => p.slice());
  for (let k = 0; k < passes; k++) {
    const n = v.length;
    if (n < 3) break;
    const out = [];
    for (let i = 0; i < n; i++) {
      if (!closed && (i === 0 || i === n - 1)) { out.push(v[i]); continue; }
      const a = v[(i - 1 + n) % n], b = v[i], c = v[(i + 1) % n];
      const t1 = Math.atan2(b[1] - a[1], b[0] - a[0]);
      const t2 = Math.atan2(c[1] - b[1], c[0] - b[0]);
      const turn = Math.abs(((t2 - t1) / D2R + 540) % 360 - 180);
      if (turn > maxTurn) { out.push(b); continue; }   // 意図した折れは保つ
      out.push([b[0] + (a[0] - b[0]) * 0.25, b[1] + (a[1] - b[1]) * 0.25],
               [b[0] + (c[0] - b[0]) * 0.25, b[1] + (c[1] - b[1]) * 0.25]);
    }
    v = out;
  }
  return closed ? v.concat([v[0].slice()]) : v;
}

